/**
 * Generates the Canvas-export runtime.
 *
 * Outputs:
 *   src/export/runtime-source.generated.js  — the runtime as a JS string constant
 *   dist/veilforge-runtime.js               — the same code as a loadable file
 *
 * Regenerating is part of `npm run build`. `npm test` fails if the committed
 * constant is stale, so an export can never silently ship yesterday's engine.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundle, hashOf } from './bundle.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(root, 'src/runtime/entry.js');

const header = `/*! VeilForge runtime — generated from src/ by tools/gen-runtime.mjs. Do not edit. */\n(function () {\n'use strict';\n`;
const footer = `\n})();\n`;

const body = bundle(entry);
const code = header + body + footer;
const hash = hashOf(code);

const distDir = path.join(root, 'dist');
fs.mkdirSync(distDir, { recursive: true });
fs.writeFileSync(path.join(distDir, 'veilforge-runtime.js'), code);

const generated = `/**
 * AUTO-GENERATED by tools/gen-runtime.mjs — do not edit by hand.
 * Runtime hash: ${hash}
 */
export const RUNTIME_HASH = ${JSON.stringify(hash)};
export const RUNTIME_SOURCE = ${JSON.stringify(code)};
`;

fs.writeFileSync(path.join(root, 'src/export/runtime-source.generated.js'), generated);

const kb = (code.length / 1024).toFixed(1);
console.log(`runtime: ${kb} KB  hash=${hash}  modules=${body.split('/* ---- ').length - 1}`);
